const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (entry.isIntersecting) entry.target.classList.add('active');
    });
}, { threshold: 0.15 });

document.querySelectorAll('.reveal').forEach(el => observer.observe(el));

document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => {
        document.querySelectorAll('.lang-btn').forEach(b => b.classList.remove('active'));
        btn.classList.add('active');
        setLanguage(btn.getAttribute('data-lang'));
    });
});

function setLanguage(lang) {
    document.querySelectorAll('[data-i18n]').forEach(elem => {
        const key = elem.getAttribute('data-i18n');
        if (translations[lang][key]) {
            if (key === "privacy-content") elem.innerHTML = translations[lang][key];
            else elem.textContent = translations[lang][key];
        }
    });
    document.documentElement.lang = lang;
}

const modal = document.getElementById("privacy-modal");
const privacyBtn = document.getElementById("privacy-btn");
const closeBtn = document.querySelector(".close-btn");
const modalBody = document.getElementById("privacy-text");

if (privacyBtn && modal) {
    privacyBtn.onclick = () => {
        const lang = document.querySelector('.lang-btn.active').getAttribute('data-lang');
        modalBody.innerHTML = translations[lang]["privacy-content"];
        modal.style.display = "block";
        document.body.style.overflow = "hidden";
    };
}

const closeModal = () => {
    modal.style.display = "none";
    document.body.style.overflow = "auto";
};

if (closeBtn) closeBtn.onclick = closeModal;
window.onclick = (e) => { if (e.target == modal) closeModal(); };

